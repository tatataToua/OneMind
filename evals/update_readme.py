"""Rewrite the README's evaluation tables from the committed report.

The README quoted `p95 2103 ms` while the report on disk said `3121.7`. Nobody
lied; the table was typed by hand after one run and the report was regenerated
by another. Any number a human retypes will eventually disagree with its source,
and a reviewer who runs the command and sees different figures has no way to
tell which kind of wrong they are looking at.

So the tables are generated. `evals/comparison_report.json` is the single source
of truth, this script projects it into the README between markers, and CI does
not need to care because the check is `--check`: it fails only if someone edited
the numbers by hand.

Usage:
    python evals/update_readme.py            # rewrite the tables
    python evals/update_readme.py --check    # fail if they are stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = Path(__file__).parent / "comparison_report.json"
README = ROOT / "README.md"

BEGIN = "<!-- eval:begin - generated by evals/update_readme.py, do not edit by hand -->"
END = "<!-- eval:end -->"

METRICS = [
    ("single-agent accuracy", "single_agent_accuracy"),
    ("multi-agent exact match", "multi_agent_exact_match"),
    ("abstain accuracy (vague prompts refused)", "abstain_accuracy"),
    ("overall exact match", "overall_exact_match"),
]


def render(report: dict) -> str:
    router = report["arms"]["router"]
    monolith = report["arms"]["monolith"]
    runs, repeat, cases = router["runs"], router["repeat"], router["cases"]

    lines = [
        BEGIN,
        "",
        f"Routing, {cases} labelled prompts against `{router['model']}`, "
        f"{repeat} attempts each ({runs} runs):",
        "",
        "| metric | result |",
        "|---|---|",
    ]
    for label, key in METRICS:
        value = f"**{router[key]}%**" if key == "single_agent_accuracy" else f"{router[key]}%"
        lines.append(f"| {label} | {value} |")
    lines += [
        f"| label precision / recall | {router['label_precision']}% / {router['label_recall']}% |",
        f"| router latency | p50 {router['latency_ms']['p50']} ms, "
        f"p95 {router['latency_ms']['p95']} ms |",
    ]
    if "stability" in router:
        lines.append(
            f"| stability (identical set on all {repeat} attempts) | **{router['stability']}%** |"
        )
    lines += [
        "",
        "Precision and recall are reported separately because their costs differ.",
        "Missing a specialist yields an incomplete answer; waking a spare one costs a",
        "few seconds and some noise.",
        "",
        "### Does the orchestration earn its keep?",
        "",
        "The same prompts, the same scorer, against one agent holding every tool and",
        "no router. Both arms get a constrained decode over the real tool",
        "descriptions and the same way to abstain — see [`evals/arms.py`](evals/arms.py)",
        "for why the baseline is not a strawman, and",
        "`backend/tests/test_eval_arms.py` for the fairness invariants pinned offline.",
        "",
        "| metric | router | monolith | delta |",
        "|---|---|---|---|",
    ]
    for label, key in METRICS:
        lines.append(_comparison_row(label, router[key], monolith[key]))
    lines += [
        _comparison_row("label precision", router["label_precision"], monolith["label_precision"]),
        _comparison_row("label recall", router["label_recall"], monolith["label_recall"]),
        f"| selection latency p50 | {router['latency_ms']['p50']} ms | "
        f"{monolith['latency_ms']['p50']} ms | "
        f"{router['latency_ms']['p50'] - monolith['latency_ms']['p50']:+.1f} ms |",
        "",
        "Regenerate with `./run.ps1 compare`, then `python evals/update_readme.py`.",
        "",
        END,
    ]
    return "\n".join(lines)


def _comparison_row(label: str, router: float, monolith: float) -> str:
    """Bold the winner, and neither on a tie.

    Bolding the router unconditionally would overstate the one metric where the
    two architectures are level, which is exactly the metric a sceptical reader
    should be able to find without reading the delta column twice.
    """
    a = f"**{router}%**" if router > monolith else f"{router}%"
    b = f"**{monolith}%**" if monolith > router else f"{monolith}%"
    return f"| {label} | {a} | {b} | {router - monolith:+.1f} |"


def splice(readme: str, block: str) -> str:
    start, end = readme.find(BEGIN), readme.find(END)
    if start == -1 or end == -1:
        raise SystemExit(f"markers not found in {README}; expected {BEGIN!r} and {END!r}")
    return readme[:start] + block + readme[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the README is stale, without rewriting it",
    )
    args = parser.parse_args()

    if not REPORT.exists():
        raise SystemExit(f"no report at {REPORT}; run ./run.ps1 compare first")

    report = json.loads(REPORT.read_text(encoding="utf-8"))
    if "arms" not in report:
        raise SystemExit(f"{REPORT} holds a single arm; regenerate it with --arm both")

    current = README.read_text(encoding="utf-8")
    updated = splice(current, render(report))

    if args.check:
        if current != updated:
            print("README evaluation tables are stale; run python evals/update_readme.py")
            return 1
        print("README evaluation tables match the report")
        return 0

    if current == updated:
        print("README already up to date")
        return 0

    README.write_text(updated, encoding="utf-8")
    print(f"rewrote the evaluation tables in {README}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
